import AppKit
import ImageIO

/// Watches the general pasteboard (macOS has no change notification, so we poll
/// `changeCount` — the same approach every clipboard manager uses) and records
/// new copies into `ClipboardStore`, skipping anything marked sensitive.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pb = NSPasteboard.general
    private var lastChangeCount = 0
    private var timer: Timer?

    /// Whether history recording is on (UserDefaults-backed, synced).
    static var isEnabled: Bool {
        get { UserDefaults.standard.object(forKey: "clipboard.enabled") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "clipboard.enabled") }
    }

    private init() {}

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pb.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Pasteboard "types" that mark transient / secret content a well-behaved
    /// clipboard manager must not store (what password managers set).
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    private static let imageTypes: Set<String> = [
        "public.png", "public.tiff", "public.jpeg", "com.compuserve.gif", "public.heic",
    ]
    /// File extensions treated as "an image file" (so a file-url to one is
    /// stored as an image, but a .md/.pdf/… stays a file).
    private static let imageExtensions: Set<String> = [
        "png", "jpg", "jpeg", "gif", "heic", "heif", "tiff", "tif", "bmp", "webp",
    ]

    private func poll() {
        let cc = pb.changeCount
        // Our own paste-back write is skipped because `writeToPasteboard` bumps
        // `lastChangeCount` to it. (A separate "ignore next change" boolean used
        // to live here; it dropped screenshots intermittently — if a screenshot
        // copy arrived as the next change after a paste-from-history, the flag
        // ate it. Relying on the changeCount alone fixes that.)
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        capture()
    }

    private func capture() {
        let types = Set((pb.types ?? []).map { $0.rawValue })
        if !types.isDisjoint(with: Self.concealedTypes) { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, ClipboardStore.excludedBundleIDs.contains(bid) { return }
        let sourceApp = front?.localizedName
        let sourceBID = front?.bundleIdentifier
        let now = Date()
        let id = UUID()

        // Resolve any file URLs once. Distinguish by extension: a real document
        // copy (.md/.pdf/…) should be a FILE even though Finder also puts a small
        // ICON image on the board; only when the file(s) are themselves images
        // (e.g. Feishu's temp .png, or copying an image file) do we treat it as
        // an image.
        let fileURLs = pb.readObjects(forClasses: [NSURL.self],
                                      options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        let onlyImageFiles = !fileURLs.isEmpty
            && fileURLs.allSatisfy { Self.imageExtensions.contains($0.pathExtension.lowercased()) }

        // 1) Non-image file(s) → FILE. (Fixes: copying a .md/doc in Finder was
        //    swallowed by the image branch because of the file's icon TIFF.)
        if !fileURLs.isEmpty, !onlyImageFiles {
            let item = ClipboardItem(id: id, kind: .file, text: nil, rtfData: nil, imageFileName: nil,
                                     filePaths: fileURLs.map { $0.path }, sourceApp: sourceApp,
                                     sourceBundleID: sourceBID, timestamp: now, charCount: 0,
                                     wordCount: 0, pinned: false)
            ClipboardStore.shared.add(item, imageData: nil)
            return
        }

        // 2) Image — real bitmap data on the board, OR file URL(s) that are all
        //    images (Feishu temp png / copying an image file). Prefer the
        //    pasteboard's decoded image; fall back to loading the file.
        if !types.isDisjoint(with: Self.imageTypes) || onlyImageFiles,
           let image = NSImage(pasteboard: pb) ?? fileURLs.first.flatMap({ NSImage(contentsOf: $0) }),
           let png = Self.pngData(from: image) {
            let item = ClipboardItem(id: id, kind: .image, text: nil, rtfData: nil, imageFileName: nil,
                                     filePaths: nil, sourceApp: sourceApp, sourceBundleID: sourceBID,
                                     timestamp: now, charCount: 0, wordCount: 0, pinned: false)
            ClipboardStore.shared.add(item, imageData: png)
            return
        }

        // 3) Any file URLs left (e.g. image file whose decode failed) → FILE.
        if !fileURLs.isEmpty {
            let item = ClipboardItem(id: id, kind: .file, text: nil, rtfData: nil, imageFileName: nil,
                                     filePaths: fileURLs.map { $0.path }, sourceApp: sourceApp,
                                     sourceBundleID: sourceBID, timestamp: now, charCount: 0,
                                     wordCount: 0, pinned: false)
            ClipboardStore.shared.add(item, imageData: nil)
            return
        }

        // 3) Text (keep the RTF too, so normal paste stays rich and "paste as
        //    plain text" can strip it).
        if let str = pb.string(forType: .string), !str.isEmpty {
            let words = str.split(whereSeparator: { $0 == " " || $0 == "\n" || $0 == "\t" }).count
            let item = ClipboardItem(id: id, kind: .text, text: str, rtfData: pb.data(forType: .rtf),
                                     imageFileName: nil, filePaths: nil, sourceApp: sourceApp,
                                     sourceBundleID: sourceBID, timestamp: now, charCount: str.count,
                                     wordCount: words, pinned: false)
            ClipboardStore.shared.add(item, imageData: nil)
        }
    }

    // MARK: Pasting back

    /// Encode straight to PNG via CGImageDestination — no full-size TIFF roundtrip.
    private static func pngData(from image: NSImage) -> Data? {
        guard let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        let data = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(data, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, cg, nil)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return data as Data
    }

    /// Write an item to the pasteboard (used before simulating ⌘V). When
    /// `asPlainText` is true, only the plain string is written (strip formatting).
    func writeToPasteboard(_ item: ClipboardItem, asPlainText: Bool = false) {
        pb.clearContents()
        switch item.kind {
        case .text:
            if !asPlainText, let rtf = item.rtfData { pb.setData(rtf, forType: .rtf) }
            if let t = item.text { pb.setString(t, forType: .string) }
        case .image:
            if let url = ClipboardStore.shared.imageURL(for: item), let img = NSImage(contentsOf: url) {
                pb.writeObjects([img])
            }
        case .file:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            if !urls.isEmpty { pb.writeObjects(urls) }
        }
        lastChangeCount = pb.changeCount
    }
}
